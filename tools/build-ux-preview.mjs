import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname,resolve} from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const saved=new Map();globalThis.localStorage={getItem:k=>saved.get(k)||null,setItem:(k,v)=>saved.set(k,v),removeItem:k=>saved.delete(k)};
const app={innerHTML:'',querySelector(){return null},querySelectorAll(){return []}};
globalThis.document={querySelector:s=>s==='#app'?app:null,scrollingElement:null};
globalThis.window={innerHeight:720,addEventListener(){}};
globalThis.requestAnimationFrame=f=>f();
const {newGame}=await import('../js/player.js');
const {header,home,world,playerMenu}=await import('../js/ui.js');
const index=readFileSync(resolve(root,'index.html'),'utf8');
const cssPaths=[...index.matchAll(/href="(css\/[^"]+\.css)"/g)].map(x=>x[1]);
const styles=cssPaths.map(path=>readFileSync(resolve(root,path),'utf8')).join('\n');
const documentHtml=(body,name)=>`<!doctype html><html lang="pt-BR"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${name}</title><style>${styles}</style></head><body><a class="ux-skip-link" href="#app">Ir para o conteúdo do jogo</a><main id="app"><header class="head">${header()}</header><div class="content">${body}</div></main></body></html>`;
writeFileSync(resolve(root,'docs/ux-preview-home.html'),documentHtml(home(),'Tela inicial'));
newGame('Aventureiro','guerreiro');
writeFileSync(resolve(root,'docs/ux-preview-world.html'),documentHtml(world(),'Aventura'));
writeFileSync(resolve(root,'docs/ux-preview-player.html'),documentHtml(playerMenu(),'Personagem'));
console.log('Prévia das três telas criada. Os arquivos são estáticos e não substituem testes de gameplay.');
