import assert from 'node:assert/strict';
const store=new Map();
globalThis.localStorage={getItem:key=>store.get(key)??null,setItem:(key,value)=>store.set(key,value),removeItem:key=>store.delete(key)};
let onClick=null;
const app={innerHTML:'',addEventListener(name,listener){if(name==='click')onClick=listener},querySelector(){return null},querySelectorAll(){return []}};
globalThis.document={querySelector:selector=>selector==='#app'?app:null};
globalThis.window={addEventListener(){}};
globalThis.requestAnimationFrame=fn=>fn();
globalThis.setInterval=()=>0;
const {rt}=await import('../js/runtime.js');
const {newGame}=await import('../js/player.js');
const {KEY}=await import('../js/data.js');
const {storylineFor,advanceAdventureExploration,advanceAdventureCombat}=await import('../js/procedural-adventures.js');
await import('../js/main.js');
assert.equal(typeof onClick,'function');
const click=action=>{const button={disabled:false,dataset:{action}};onClick({target:{closest:()=>button}})};
newGame('Interações','guerreiro');
const story=storylineFor(rt.state,0);
rt.screen='tavern';
click(`tavernGuest:${story.sourceGuest}`);
assert.equal(rt.state.adventure.entries[story.id].phase,'available');
assert.equal(JSON.parse(store.get(KEY)).adventure.entries[story.id].phase,'available');
click(`adventureAccept:${story.id}`);
assert.equal(rt.state.adventure.entries[story.id].phase,'investigate');
assert.equal(JSON.parse(store.get(KEY)).adventure.entries[story.id].phase,'investigate');
assert.equal(advanceAdventureExploration(rt.state,0,()=>0).kind,'clue');
assert.equal(advanceAdventureExploration(rt.state,0,()=>0).complete,true);
if(story.type==='delivery'){
 click(`adventureDeliver:${story.id}`);
}else{
 const e1={humanoid:true};rt.state.combat={enemy:e1};advanceAdventureCombat(rt.state,0,e1);
 const e2={humanoid:true};rt.state.combat={enemy:e2};advanceAdventureCombat(rt.state,0,e2);
 rt.state.combat=null;
}
assert.equal(rt.state.adventure.entries[story.id].phase,'decision');
rt.screen='quests';
const beforeGold=rt.state.gold,beforeXp=rt.state.xp;
click(`adventureClaim:${story.id}:report`);
const after={gold:rt.state.gold,level:rt.state.lv,xp:rt.state.xp};
assert.ok(after.gold>beforeGold);
assert.ok(after.xp>beforeXp||after.level>1);
assert.equal(rt.state.adventure.entries[story.id].phase,'done');
assert.equal(JSON.parse(store.get(KEY)).adventure.entries[story.id].phase,'done');
click(`adventureClaim:${story.id}:report`);
assert.deepEqual({gold:rt.state.gold,level:rt.state.lv,xp:rt.state.xp},after);
assert.equal(rt.state.adventure.completed.length,1);
rt.screen='tavern';
const {tavernUI}=await import('../js/ui.js');
assert.ok(tavernUI().includes(story.endings.report),'O visitante deve reconhecer a decisão tomada.');
console.log('OK: cliques reais no handler principal, conversa, aceitação, conclusão por caça/entrega, recompensa e persistência sem duplicação.');
