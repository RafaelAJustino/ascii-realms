import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const store=new Map();
globalThis.localStorage={getItem:key=>store.get(key)||null,setItem:(key,val)=>store.set(key,val),removeItem:key=>store.delete(key)};
const app={innerHTML:'',addEventListener(){},querySelector(){return null},querySelectorAll(){return []}};
globalThis.document={querySelector:selector=>selector==='#app'?app:null};
globalThis.window={innerHeight:844,addEventListener(){}};
globalThis.requestAnimationFrame=fn=>fn();
const {rt}=await import('../js/runtime.js');
const {newGame}=await import('../js/player.js');
const {combat,act}=await import('../js/combat.js');
const {combatUI,combatQuickControls}=await import('../js/ui.js');
const {playerCooldownDetails}=await import('../js/turn-cooldowns.js');
const {setCombatSpeed}=await import('../js/combat-speed.js');
newGame('Herói de Teste','guerreiro');
setCombatSpeed('instant');
combat();
assert.equal(rt.screen,'combat');
assert.equal(rt.float,null,'dano antigo não reaparece na entrada');
let html=combatUI();
assert.match(html,/class="combat-arena"/,'mantém arena única da Etapa anterior');
assert.equal((html.match(/data-action="attack"/g)||[]).length,1,'ataque comum diretamente disponível');
assert.equal((html.match(/data-action="skill:\d"/g)||[]).length,4,'quatro habilidades acessíveis sem abrir submenu');
assert.ok(!html.includes('data-action="submenu:attack"'),'não obriga o jogador a navegar para atacar');
assert.ok(html.indexOf('data-action="attack"')<html.indexOf('data-action="skill:0"'));
assert.match(html,/ux-combat-latest/);
assert.match(html,/Um .* apareceu!/,'histórico inicial mostra somente aparição');
assert.ok(!html.includes('floating-damage enemy'));
assert.match(html,/data-panel="history"/,'histórico nativo expansível');
assert.match(html,/data-panel="items"/,'consumíveis agrupados');
for(const type of ['hp','mp','elixir','antidote'])assert.ok(html.includes(`data-action="potion:${type}"`));
assert.match(html,/data-action="flee"/);
assert.match(html,/data-action="combatSpeed:/);
assert.match(html,/Disponível no nível/,'habilidade indisponível mostra a razão');
rt.state.lv=20;
rt.state.mp=0;
html=combatQuickControls();
assert.match(html,/Mana insuficiente/);
rt.state.mp=999;
const cd=playerCooldownDetails(rt.state,0);
rt.state.combat.cooldowns[cd.id]=2;
html=combatQuickControls();
assert.match(html,/Recarga: 2 turnos/);
rt.state.combat.cooldowns[cd.id]=0;
rt.state.combat.enemy.boss=true;
html=combatQuickControls();
assert.match(html,/Indisponível nesta batalha/);
assert.match(html,/data-action="flee"[^>]*disabled/);
rt.state.combat.enemy.boss=false;
rt.state.hp=9999;
rt.state.combat.enemy.hp=99999;
rt.state.combat.enemy.atk=0;
const previous=rt.state.combat.turn;
await act('attack');
assert.equal(rt.state.combat.turn,previous+1,'ação direta mantém motor de turnos');
assert.equal(rt.float,null,'feedback de dano não permanece após turno');
assert.match(combatUI(),/Último acontecimento|ÚLTIMO ACONTECIMENTO/);
assert.ok(store.get('ascii-realms-save-v1'),'salvamento antigo permanece');
const styles=readFileSync(new URL('../css/mobile-combat-stage5.css',import.meta.url),'utf8');
assert.match(styles,/grid-template-columns: repeat\(2, minmax\(0, 1fr\)\)/);
assert.match(styles,/min-height: 44px/);
assert.match(styles,/overflow-y: auto/);
assert.match(styles,/prefers-reduced-motion/);
assert.doesNotMatch(styles,/position:\s*fixed/);
assert.match(readFileSync(new URL('../index.html',import.meta.url),'utf8'),/mobile-combat-stage5\.css/);
assert.match(readFileSync(new URL('../js/ui.js',import.meta.url),'utf8'),/openedCombatDetails/);
console.log('OK: Etapa 5, arena preservada, ataque direto, 4 habilidades, disponibilidade, cooldowns, consumíveis, fuga, histórico, feedback, turnos, LocalStorage e CSS mobile.');
