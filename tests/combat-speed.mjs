import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {COMBAT_SPEED_KEY,COMBAT_SPEEDS,getCombatSpeed,initCombatSpeed,setCombatSpeed,combatTimings,visualPause} from '../js/combat-speed.js';
const store = new Map();
const storage = {getItem:key=>store.get(key)??null,setItem:(key,value)=>store.set(key,value)};
assert.deepEqual(Object.keys(COMBAT_SPEEDS),['normal','fast','instant']);
assert.equal(initCombatSpeed(storage),'fast');
assert.equal(getCombatSpeed(),'fast');
assert.equal(setCombatSpeed('normal',storage),true);
assert.equal(store.get(COMBAT_SPEED_KEY),'normal');
assert.ok(combatTimings().enemyPrepare>COMBAT_SPEEDS.fast.enemyPrepare);
assert.equal(setCombatSpeed('instant',storage),true);
assert.deepEqual(Object.values(combatTimings()).filter(v=>typeof v==='number'),[0,0,0,0]);
assert.equal(setCombatSpeed('invalid',storage),false);
assert.equal(getCombatSpeed(),'instant');
assert.equal(initCombatSpeed(storage),'instant');
await visualPause(0);
assert.equal(initCombatSpeed({getItem(){throw Error('storage unavailable')}}),'fast');
const combat=readFileSync(new URL('../js/combat.js',import.meta.url),'utf8');
const ui=readFileSync(new URL('../js/ui.js',import.meta.url),'utf8');
const main=readFileSync(new URL('../js/main.js',import.meta.url),'utf8');
const exploration=readFileSync(new URL('../js/exploration.js',import.meta.url),'utf8');
const css=readFileSync(new URL('../css/combat-speed.css',import.meta.url),'utf8');
assert.ok(combat.includes('combatTimings().enemyPrepare'),'enemy turn preparation uses selected speed');
assert.ok(combat.includes('playCombatAction')&&combat.includes('playCombatReaction'),'visual sequence uses selected speed and action-specific effects');
assert.ok(!combat.includes('delay(950)'));
assert.ok(combat.includes("c.turn++;"));
assert.ok(combat.includes("if(rt.busy||!rt.state?.combat)return"));
assert.ok(ui.includes('combat-speed-options')&&ui.includes('aria-pressed'));
assert.ok(main.includes("action==='combatSpeed'"));
assert.ok(css.includes('grid-template-columns:repeat(3,minmax(0,1fr))'));
assert.ok(ui.includes('VOLTAR PARA INÍCIO'));
assert.ok(exploration.includes("endJourney(rt.state);rt.screen='world'"));
assert.ok(main.includes('returnToHome();'));
console.log('OK: velocidades, padrão rápido, persistência independente, instantâneo, tempos, bloqueio por turno, retorno à tela inicial.');
