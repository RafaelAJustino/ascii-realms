import assert from 'node:assert/strict';
import {EPIC_EVENTS} from '../js/epic-events.js';
import {EVENT_BY_ID,narrativeDefaults,availableEvents,pickNarrativeEvent,canChoose,resolveNarrativeChoice,normalizeNarrative} from '../js/journey-events.js';
import {regionSpecies} from '../js/expanded-species.js';
import {normalizeSave} from '../js/state-schema.js';
const state={version:12,cls:'guerreiro',name:'Narrador',lv:8,area:1,stats:[8,2,3,9,8,3],xp:0,gold:60,hp:80,mp:10,points:0,items:[],equip:{},materials:{},bosses:[],consumables:{hp:1,mp:1},journey:{path:'unknown',area:1,steps:3,last:[],event:null},narrative:narrativeDefaults()};
assert.equal(EPIC_EVENTS.length,20);
assert.equal(new Set(EPIC_EVENTS.map(x=>x.id)).size,EPIC_EVENTS.length);
for(const e of EPIC_EVENTS){assert.ok(e.title&&e.description);assert.ok(e.choices.length>=2&&e.choices.length<=4);assert.equal(new Set(e.choices.map(c=>c.id)).size,e.choices.length);assert.ok(e.regions.every(n=>n>=0&&n<10));assert.ok(EVENT_BY_ID[e.id]);}
assert.ok(availableEvents(state).some(x=>x.id==='road-toll'));
assert.ok(!availableEvents(state).some(x=>x.id==='bandit-hideout'));
state.journey.event='road-toll';
assert.equal(canChoose(state,'road-toll','pay'),true);
assert.equal(canChoose(state,'road-toll','intimidate'),true);
const payment=resolveNarrativeChoice(state,'road-toll','pay',{maxhp:100,maxmp:30,materialName:'Madeira Antiga'});
assert.equal(payment.combat,false);assert.equal(state.gold,25);
assert.equal(resolveNarrativeChoice(state,'road-toll','pay',{maxhp:100,maxmp:30,materialName:'Madeira Antiga'}),null);
assert.equal(state.gold,25);
state.journey.event='caravan-ledger';
assert.ok(resolveNarrativeChoice(state,'caravan-ledger','keep',{maxhp:100,maxmp:30,materialName:'Madeira Antiga'}));
assert.equal(state.narrative.flags.banditLedger,true);
assert.ok(availableEvents(state).some(x=>x.id==='bandit-hideout'));
state.journey.event='bandit-hideout';
assert.equal(canChoose(state,'bandit-hideout','spy'),true);
state.stats[3]=7;assert.equal(canChoose(state,'bandit-hideout','spy'),false);
assert.equal(resolveNarrativeChoice(state,'bandit-hideout','spy',{maxhp:100,maxmp:30,materialName:'Madeira Antiga'}),null);
assert.equal(canChoose(state,'bandit-hideout','assault'),true);
const attack=resolveNarrativeChoice(state,'bandit-hideout','assault',{maxhp:100,maxmp:30,materialName:'Madeira Antiga'});
assert.equal(attack.combat,true);assert.equal(attack.enemyKind,'bandit');
assert.ok(regionSpecies(0).some(spec=>spec.humanoid));
state.journey.path='safe';assert.ok(!availableEvents(state).some(x=>x.id==='road-toll'));
state.journey.area=71;state.area=71;assert.ok(availableEvents(state).some(e=>e.id==='ashen-offering'));
assert.ok(!availableEvents(state).some(e=>e.id==='frozen-camp'));
const saved=normalizeSave({...state,combat:null});assert.equal(saved.narrative.flags.banditLedger,true);
assert.ok(saved.narrative.completed.includes('bandit-hideout'));
assert.equal(normalizeNarrative(saved.narrative).completed.filter(x=>x==='road-toll').length,1);
assert.equal(pickNarrativeEvent({...state,narrative:{...state.narrative,completed:EPIC_EVENTS.map(e=>e.id)}},()=>0).id,'wounded-traveler');
console.log('OK: 20 novos eventos, filtros de região e caminho, cadeia de bandidos, custo, atributos, combate humanoide, idempotência e salvamento.');
