import assert from 'node:assert/strict';
const store=new Map();
globalThis.localStorage={getItem:key=>store.get(key)??null,setItem:(key,value)=>store.set(key,value),removeItem:key=>store.delete(key)};
const app={innerHTML:'',addEventListener(){},querySelector(){return null},querySelectorAll(){return []}};
globalThis.document={querySelector:selector=>selector==='#app'?app:null};
globalThis.window={addEventListener(){}};
globalThis.requestAnimationFrame=fn=>fn();
const {rt}=await import('../js/runtime.js');
const {newGame}=await import('../js/player.js');
const {save,load}=await import('../js/storage.js');
const {KEY}=await import('../js/data.js');
const {talkToGuest}=await import('../js/tavern-stories.js');
const {questUI}=await import('../js/progression-ui.js');
const {tavernUI}=await import('../js/ui.js');
const {storylineFor,discoverAdventure,acceptAdventure,advanceAdventureExploration,deliverAdventure}=await import('../js/procedural-adventures.js');

newGame('Heroi Procedural','arqueiro');
assert.equal(rt.state.version,14);
assert.equal(typeof rt.state.adventure.seed,'number');
const seed=rt.state.adventure.seed;
const story=storylineFor(rt.state,0);
assert.ok(tavernUI().includes('AVENTURAS PESSOAIS'));
assert.ok(questUI().includes('Uma história secundária está oculta'));
const conversation=talkToGuest(rt.state,0,story.sourceGuest);
assert.ok(conversation?.message);
assert.equal(discoverAdventure(rt.state,0,'guest',story.sourceGuest)?.id,story.id);
assert.ok(questUI().includes(story.title));
assert.ok(questUI().includes(`adventureAccept:${story.id}`));
assert.ok(tavernUI().includes(`adventureAccept:${story.id}`));
assert.equal(acceptAdventure(rt.state,0,story.id),true);
assert.ok(questUI().includes('Pistas descobertas: 0/2'));
assert.equal(advanceAdventureExploration(rt.state,0,()=>0).kind,'clue');
assert.ok(questUI().includes('Pistas descobertas: 1/2'));
assert.equal(save(),true);
assert.equal(JSON.parse(store.get(KEY)).adventure.entries[story.id].clues.length,1);
rt.state=null;
assert.equal(load(),true);
assert.equal(rt.state.adventure.seed,seed);
assert.equal(rt.state.adventure.entries[story.id].clues.length,1);
assert.ok(questUI().includes('Pistas descobertas: 1/2'));
assert.equal(advanceAdventureExploration(rt.state,0,()=>0).complete,true);
if(story.type==='delivery'){
 assert.ok(tavernUI().includes('Entregar correspondência'));
 assert.ok(deliverAdventure(rt.state,0,story.id));
}else{
 assert.ok(questUI().includes('Humanoides hostis derrotados: 0/2'));
 const foe={humanoid:true,boss:false};
 const {advanceAdventureCombat}=await import('../js/procedural-adventures.js');
 rt.state.combat={enemy:foe};assert.ok(advanceAdventureCombat(rt.state,0,foe));
 rt.state.combat={enemy:{humanoid:true}};assert.ok(advanceAdventureCombat(rt.state,0,rt.state.combat.enemy));
 rt.state.combat=null;
}
assert.ok(questUI().includes(`adventureClaim:${story.id}:report`));
assert.ok(questUI().includes(`adventureClaim:${story.id}:protect`));
assert.ok(!questUI().includes('companheiros'));
assert.equal(save(),true);
rt.state=null;assert.equal(load(),true);
assert.ok(questUI().includes(`adventureClaim:${story.id}:report`));
console.log('OK: jogo novo, semente persistente, conversa de taverna, aceitação, interface, duas pistas, objetivo final e recarga v14.');
