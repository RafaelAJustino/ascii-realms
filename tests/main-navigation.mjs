import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const saved=new Map();
globalThis.localStorage={getItem:k=>saved.get(k)||null,setItem:(k,v)=>saved.set(k,v),removeItem:k=>saved.delete(k)};
const app={innerHTML:'',querySelector(){return null},querySelectorAll(){return []}};
globalThis.document={querySelector:s=>s==='#app'?app:null};
globalThis.window={innerHeight:667,addEventListener(){}};
globalThis.requestAnimationFrame=f=>f();
const {rt}=await import('../js/runtime.js');
const {newGame}=await import('../js/player.js');
const {home,world,playerMenu,render}=await import('../js/ui.js');
assert.match(home(),/start-actions/);
assert.match(home(),/disabled data-action="continue"/);
assert.match(home(),/data-action="create"/);
assert.match(home(),/data-action="delete" disabled/);
newGame('Teste','guerreiro');
assert.match(home(),/data-action="continue"/);
assert.doesNotMatch(home(),/disabled data-action="continue"/);
let main=world();
assert.match(main,/main-actions/);
assert.ok(main.indexOf('> Explorar')<main.indexOf('# Selecionar Mapa'));
assert.ok(main.indexOf('# Selecionar Mapa')<main.indexOf('H Visitar Cidade'));
assert.ok(main.indexOf('H Visitar Cidade')<main.indexOf('@ Jogador'));
for(const action of ['explore','maps','city','nav:player'])assert.ok(main.includes(`data-action="${action}"`));
let player=playerMenu();
for(const action of ['character','inventory','skills','quests','bestiary','statistics','specializations'])assert.ok(player.includes(`data-action="nav:${action}"`));
assert.ok(player.includes('nav:world'));
rt.screen='player';render();assert.doesNotMatch(app.innerHTML,/<nav\b/);
rt.screen='world';render();assert.doesNotMatch(app.innerHTML,/<nav\b/);
rt.screen='maps';rt.returnScreen='world';render();assert.ok(app.innerHTML.includes('data-action="menuBack"'));
rt.screen='character';rt.returnScreen='player';render();assert.ok(app.innerHTML.includes('data-action="menuBack"'));
const css=readFileSync(new URL('../css/navigation-main.css',import.meta.url),'utf8');
assert.match(css,/grid-template-columns:repeat\(2,minmax\(0,1fr\)\)/);
assert.match(css,/grid-column:1\/-1/);
assert.match(css,/gap:var\(--nav-gap\)/);
assert.match(css,/--nav-button-height:42px/);
assert.match(css,/max-height:50px/);
assert.match(css,/#app \.nav\{display:none\}/);
console.log('OK: entrada, navegação principal, menu Jogador, retorno, remoção de barra e estilos responsivos.');
