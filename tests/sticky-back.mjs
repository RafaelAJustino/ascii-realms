import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {rememberMenu,previousMenu,clearMenuHistory,fallbackMenu} from '../js/menu-history.js';
const read=p=>readFileSync(new URL(p,import.meta.url),'utf8');
const css=read('../css/menu-sticky.css'),ui=read('../js/ui.js'),main=read('../js/main.js'),html=read('../index.html');
assert.match(css,/\.menu-back-container\s*\{[^}]*position:sticky/);
assert.match(css,/top:0/);
assert.doesNotMatch(css,/position:\s*fixed/);
assert.match(css,/height:42px/);
assert.match(ui,/menu-back-container/);
assert.match(ui,/data-action=\\?"menuBack/);
assert.match(ui,/\['world','home','combat','result','journey'\]/);
assert.match(main,/action==='menuBack'/);
assert.match(main,/confirmLeave\(confirm\)/);
assert.match(html,/menu-sticky\.css/);
clearMenuHistory();rememberMenu('world','weapon',91);rememberMenu('player','weapon',132);
assert.deepEqual(previousMenu(),{screen:'player',shop:'weapon',scroll:132});
assert.deepEqual(previousMenu(),{screen:'world',shop:'weapon',scroll:91});
assert.equal(previousMenu(),null);
assert.equal(fallbackMenu('character'),'player');
assert.equal(fallbackMenu('forge'),'city');
console.log('OK: botão sticky dentro do contêiner rolável, 42px, histórico de navegação, confirmação de atributos e retorno.');
