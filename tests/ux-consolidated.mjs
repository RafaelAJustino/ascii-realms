import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const saved=new Map(),listeners={};
globalThis.localStorage={getItem:k=>saved.get(k)??null,setItem:(k,v)=>saved.set(k,String(v)),removeItem:k=>saved.delete(k)};
const app={innerHTML:'',addEventListener:(name,fn)=>listeners[name]=fn,querySelector:()=>null,querySelectorAll:()=>[]};
globalThis.document={querySelector:key=>key==='#app'?app:null,querySelectorAll:()=>[],scrollingElement:null};
globalThis.window={innerHeight:844,addEventListener:()=>{}};
globalThis.requestAnimationFrame=fn=>fn();globalThis.setInterval=()=>0;globalThis.confirm=()=>true;
const {rt}=await import('../js/runtime.js');
const {newGame}=await import('../js/player.js');
const {QUESTS,acceptQuest}=await import('../js/progression.js');
const {world,render}=await import('../js/ui.js');
const {uxPrefs,trackedQuest,guideForScreen}=await import('../js/ux-consolidated.js');
const {sectionNavigation}=await import('../js/navigation-sections.js');
await import('../js/main.js');
const click=action=>listeners.click({target:{closest(){return {disabled:false,dataset:{action}};}}});
newGame('Nova UI','ladino');
assert.equal(rt.state.version,14);
assert.match(app.innerHTML,/ux-world-hero-card/);
assert.match(app.innerHTML,/ux-world-goal/);
assert.match(app.innerHTML,/ux-world-vitals/);
assert.match(sectionNavigation('world',rt.state),/class="ux-icon"/);
assert.equal((sectionNavigation('world',rt.state).match(/tabindex="-1"/g)||[]).length,4);
assert.match(guideForScreen('world'),/Primeiros passos/);
click('uxDismissTip:world');
assert.equal(guideForScreen('world'),'');
click('uxSettingsOpen');assert.equal(rt.showSettings,true);
assert.match(app.innerHTML,/class="ux-settings-overlay"/);
click('uxPref:largeText');assert.equal(uxPrefs().largeText,true);
click('uxPref:reducedMotion');assert.equal(uxPrefs().reducedMotion,true);
click('uxSettingsClose');assert.equal(rt.showSettings,false);
assert.doesNotMatch(app.innerHTML,/class="ux-settings-overlay"/);
const q=QUESTS[0];
assert.equal(acceptQuest(q.id),true);
assert.match(world(),new RegExp(q.description));
assert.equal(trackedQuest(rt.state,0).id,q.id);
assert.equal(saved.get('ascii-realms-save-v1')!=null,true);
click(`uxTrackQuest:${q.id}`);
assert.equal(trackedQuest(rt.state,0).id,q.id);
click('navArea:mundo');assert.equal(rt.screen,'atlas');
click('nav:tavern');click('navArea:mundo');assert.equal(rt.screen,'atlas');
click('navArea:aventura');assert.equal(rt.screen,'world');
assert.match(app.innerHTML,/ux-world-place-card/);
assert.match(readFileSync(new URL('../index.html',import.meta.url),'utf8'),/ux-consolidated.css/);
assert.match(readFileSync(new URL('../css/ux-consolidated.css',import.meta.url),'utf8'),/position:fixed/);
console.log('OK: UX consolidada, cards, navegação, primeiro clique, preferências, dicas, acompanhamento e salvamento v14.');
