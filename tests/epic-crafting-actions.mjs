import assert from 'node:assert/strict';
const storage=new Map();
globalThis.localStorage={getItem:k=>storage.get(k)??null,setItem:(k,v)=>storage.set(k,v),removeItem:k=>storage.delete(k)};
let clickListener=null;
const app={innerHTML:'',addEventListener(event,fn){if(event==='click')clickListener=fn},querySelector(){return null},querySelectorAll(){return []}};
globalThis.document={querySelector:s=>s==='#app'?app:null};
globalThis.window={addEventListener(){}};
globalThis.requestAnimationFrame=fn=>fn();
globalThis.setInterval=()=>0;
const {rt}=await import('../js/runtime.js');
const {newGame}=await import('../js/player.js');
const {recipes}=await import('../js/crafting.js');
const {ARTISAN_CATALYSTS,materialMarket,refiningCost}=await import('../js/artisan-economy.js');
const {maps,KEY}=await import('../js/data.js');
const {forgeUI,city}=await import('../js/ui.js');
await import('../js/main.js');
const click=action=>{const button={disabled:false,dataset:{action}};clickListener({target:{closest:()=>button}})};
newGame('Mercadora','arqueiro');rt.state.lv=10;rt.state.gold=100000;rt.area=1;rt.screen='forge';
rt.state.materials[maps[0][6]]=80;rt.state.materials['Ferro Bruto']=80;
const html=forgeUI();
assert.match(html,/FABRICAÇÃO ARTESANAL/);
assert.match(html,/REFINO DE CATALISADORES/);
assert.match(html,/Kit de sobrevivência/);
assert.equal((html.match(/data-action="craft:/g)||[]).length,18);
const refine=refiningCost(0),beforeGold=rt.state.gold;
click('refine');
assert.equal(rt.state.gold,beforeGold-refine.gold);
assert.equal(rt.state.materials[ARTISAN_CATALYSTS[0]],1);
const id=recipes(0,'arqueiro').find(x=>x.modelId).id;
click(`craft:${id}`);
const crafted=rt.state.items.at(-1);
assert.equal(crafted.catalogId,recipes(0,'arqueiro').find(x=>x.id===id).modelId);
assert.equal(JSON.parse(storage.get(KEY)).items.at(-1).catalogId,crafted.catalogId);
rt.screen='city';rt.shop='materials';
const cityUI=city();assert.match(cityUI,/MERCADO DE INSUMOS/);
assert.match(cityUI,/Materiais/);
const offer=materialMarket(0)[2];
assert.match(cityUI,new RegExp(`buyMaterial:${encodeURIComponent(offer.name)}`));
const gold=rt.state.gold;
click(`buyMaterial:${encodeURIComponent(offer.name)}`);
assert.equal(rt.state.gold,gold-offer.price);
assert.equal(rt.state.materials[offer.name],1);
rt.area=11;rt.state.area=11;
const before=rt.state.gold;
click(`buyMaterial:${encodeURIComponent(offer.name)}`);
assert.equal(rt.state.gold,before,'não comprar estoque de outra região');
console.log('OK: botões reais de refino, fabricação e compra; catálogo visível, modelo entregue, custo cobrado e salvamento no LocalStorage.');
