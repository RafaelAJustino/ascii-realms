import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {worldClimateDefaults,normalizeWorldClimate,timeOfDay,regionWeather,regionalEvent,regionConditions,encounterChance,narrativeChance,advanceWorldClimate,TICKS_PER_DAY,REGION_EVENT_DURATION} from '../js/world-climate.js';
import {normalizeSave,SAVE_VERSION} from '../js/state-schema.js';
const read=filename=>readFileSync(new URL(filename,import.meta.url),'utf8');
assert.equal(SAVE_VERSION,12);
const sample={version:9,name:'Teste',cls:'guerreiro',lv:1,xp:0,gold:100,stats:[10,10,10,10,10,10],points:0,hp:50,mp:30,area:1,items:[],equip:{},journey:{path:'safe',area:1,steps:0,last:[],event:null}};
const state=normalizeSave(sample);
assert.deepEqual(state.worldClimate,worldClimateDefaults());
assert.equal(state.journey.path,'safe');
assert.equal(timeOfDay(state).period,'Dia');
assert.equal(timeOfDay(state).day,1);
const firstWeather=regionWeather(state,0);
assert.ok(['clear','rain','fog','storm'].includes(firstWeather));
// O relógio nao avanca ao calcular condicoes / simular interfaces.
for(let i=0;i<5;i++)regionConditions(state,0);
assert.equal(state.worldClimate.tick,0);
for(let i=0;i<TICKS_PER_DAY;i++)advanceWorldClimate(state,0,()=>1);
assert.equal(state.worldClimate.tick,TICKS_PER_DAY);
assert.equal(timeOfDay(state).day,2);
// Sorteio de evento somente nas janelas elegiveis, sem repeticao durante validade.
const eventState={worldClimate:worldClimateDefaults()};
for(let i=0;i<5;i++)assert.equal(advanceWorldClimate(eventState,0,()=>0).announcement,null);
const announced=advanceWorldClimate(eventState,0,()=>0);
assert.match(announced.announcement,/Acontecimento regional/);
assert.equal(regionalEvent(eventState,0).remaining,REGION_EVENT_DURATION);
assert.equal(eventState.worldClimate.history.length,1);
const eid=regionalEvent(eventState,0).id;
for(let i=0;i<5;i++)advanceWorldClimate(eventState,0,()=>0);
assert.equal(regionalEvent(eventState,0).id,eid,'Evento permanece ativo e unico');
assert.equal(eventState.worldClimate.history.length,1);
for(let i=0;i<2;i++)advanceWorldClimate(eventState,0,()=>1);
assert.equal(regionalEvent(eventState,0),null,'Evento expira apos duracao definida');
const normalized=normalizeWorldClimate({tick:18,events:{0:{id:'festival',expires:21},1:{id:'unknown',expires:99},2:{id:'incursion',expires:12},evil:{id:'festival',expires:20}},history:['a',null,'b']});
assert.deepEqual(normalized.events,{'0':{id:'festival',expires:21}});
assert.deepEqual(normalized.history,['a','b']);
assert.ok(encounterChance(.72,{risk:-10})===0);
assert.ok(encounterChance(.86,{risk:10})===1);
assert.ok(narrativeChance(.7,{narrative:100})===1);
assert.ok(narrativeChance(.7,{narrative:0})===0);
assert.notEqual(encounterChance(.8,regionConditions({worldClimate:{tick:7,events:{}}},0)),.8,'Clima/noite alteram risco');
const migrated=normalizeSave({...sample,version:10,companions:{recruited:['lina'],active:'lina'},worldClimate:{tick:7,events:{0:{id:'festival',expires:10}},history:['Antigo evento']}});
assert.equal(migrated.version,12);
assert.ok(!Object.hasOwn(migrated,'companions'),'Descarta dados da etapa anterior de companheiros');
assert.equal(migrated.worldClimate.tick,7);
assert.equal(migrated.worldClimate.events['0'].id,'festival');
assert.ok(!read('../js/main.js').includes('companion'));
assert.ok(!read('../js/combat.js').includes('companion'));
assert.ok(!read('../js/ui.js').includes('companion'));
assert.ok(read('../js/exploration.js').includes('advanceWorldClimate'));
assert.ok(read('../js/ui.js').includes('climateSummary'));
assert.ok(read('../index.html').includes('world-climate.css'));
console.log('OK: etapa 7 refeita sem companheiros, clima, dia/noite, eventos regionais, limites, persistencia, migracao e interface.');
