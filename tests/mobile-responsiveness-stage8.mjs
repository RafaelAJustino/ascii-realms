import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {SCREEN_LABELS,screenHeadingLabel,enhanceMobileAccessibility} from '../js/mobile-accessibility-stage8.js';
const file=path=>readFileSync(new URL(`../${path}`,import.meta.url),'utf8');
const html=file('index.html'),css=file('css/mobile-responsiveness-stage8.css'),ui=file('js/ui.js'),main=file('js/main.js');
assert.equal(screenHeadingLabel('combat'),'Combate');
assert.equal(screenHeadingLabel('quests'),'Missões');
assert.equal(screenHeadingLabel('inventory'),'Inventário');
assert.equal(screenHeadingLabel('unknown'),'Aventura');
assert.ok(Object.keys(SCREEN_LABELS).length>=25);
assert.doesNotThrow(()=>enhanceMobileAccessibility({querySelectorAll:()=>[],querySelector:()=>null},'combat'));
assert.doesNotThrow(()=>enhanceMobileAccessibility({querySelectorAll:()=>[],querySelector:()=>({})},'city')); // simuladores legados de DOM
assert.match(html,/href="#game-content"/);
assert.match(html,/css\/mobile-responsiveness-stage8\.css/);
assert.ok(html.indexOf('mobile-city-quests-stage7.css')<html.indexOf('mobile-responsiveness-stage8.css'));
assert.match(ui,/id="game-content" tabindex="-1"/);
assert.match(ui,/class="ux8-screen-heading" tabindex="-1"/);
assert.match(ui,/enhanceMobileAccessibility\(rt\.app,rt\.screen\)/);
assert.match(ui,/focusFromPreviousScreen/);
assert.match(ui,/el\.setAttribute\('aria-hidden','true'\)/);
assert.match(ui,/container\.setAttribute\('role','img'\)/);
assert.match(ui,/container\.setAttribute\('aria-label',`Ampliar arte ASCII/);
assert.match(main,/addEventListener\('keydown'/);
assert.match(main,/event\.key!=='Escape'/);
assert.match(main,/details\.open=false/);
assert.match(css,/@media \(prefers-contrast:more\)/);
assert.match(css,/@media \(forced-colors:active\)/);
assert.match(css,/@media \(prefers-reduced-motion:reduce\)/);
assert.match(css,/combat-speed-option \{ height:44px!important;min-height:44px!important/);
assert.match(css,/safe-area-inset-left/);
assert.match(css,/min-width:0/);
assert.doesNotMatch(css,/\.ascii-art\s*\{\s*display:\s*none/);
assert.match(file('js/storage.js'),/version/);
console.log('OK: Etapa 8, semântica de telas, foco, arte ASCII, escape, estados, velocidade, toque, contraste, movimentos e save compatível.');
