import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {TELEGRAPH_PROBABILITY,MONSTER_PATTERNS,selectAnnouncedAction,announceMonsterAction,consumeAnnouncedAction,resolveElementReaction,observedElementLabel} from '../js/combat-tactics.js';
import {finishMonsterAction} from '../js/monster-ai.js';
globalThis.document={querySelector:()=>null};
globalThis.window={addEventListener(){}};
globalThis.requestAnimationFrame=f=>f();
const {observeMonsterAction,observeMonsterAffinity}=await import('../js/progression.js');
const {bestiaryUI}=await import('../js/progression-ui.js');
const {rt}=await import('../js/runtime.js');
const {normalizeSave}=await import('../js/state-schema.js');

assert.deepEqual(Object.keys(TELEGRAPH_PROBABILITY),['elite','champion','legendary']);
assert.equal(Object.keys(MONSTER_PATTERNS).length,6);
const base={name:'Aranha',baseName:'Aranha',hp:200,maxhp:200,lv:25,atk:70,rarityId:'champion',mp:80,maxmp:80,cooldowns:{},effects:[],boss:false,attackElement:'poison'};
const monster=structuredClone(base);
assert.equal(selectAnnouncedAction({...monster,rarityId:'common'},{random:()=>0}),null);
assert.equal(selectAnnouncedAction({...monster,boss:true},{random:()=>0}),null);
assert.equal(selectAnnouncedAction(monster,{random:()=>.99}),null);
assert.equal(selectAnnouncedAction({...monster,mp:0},{random:()=>0}),null);
assert.equal(selectAnnouncedAction({...monster,telegraphCooldown:2},{random:()=>0}),null);
const action=selectAnnouncedAction(monster,{random:()=>0});
assert.ok(action&&action.power>=1.3&&action.kind==='damage');
const mpBefore=monster.mp;
assert.equal(announceMonsterAction(monster,action),true);
assert.equal(monster.mp,mpBefore,'Anunciar não gasta MP');
assert.equal(selectAnnouncedAction(monster,{random:()=>0}),null,'Não anunciar duas vezes');
assert.match(monster.telegraph.message,/um turno para reagir/);
const resolved=consumeAnnouncedAction(monster);
assert.equal(resolved.id,action.id);
assert.equal(monster.telegraph,null);
assert.equal(monster.telegraphCooldown,4);
finishMonsterAction(monster,resolved);
assert.equal(monster.mp,mpBefore-resolved.cost,'Gastar MP uma vez ao executar');
assert.equal(consumeAnnouncedAction(monster),null);
assert.equal(selectAnnouncedAction(monster,{random:()=>0}),null,'Respeitar tempo entre anúncios');

const target={hp:100,effects:[{type:'poison',power:.03,duration:2},{type:'burn',power:.03,duration:2}]};
let result=resolveElementReaction(target,'fire',30);
assert.equal(result.bonus,6);assert.equal(target.hp,94);
assert.deepEqual(target.effects.map(x=>x.type),['burn']);
assert.equal(resolveElementReaction(target,'fire',30).bonus,0,'Não repetir reação');
result=resolveElementReaction(target,'ice',30);
assert.equal(result.bonus,3);assert.equal(target.hp,91);
assert.equal(target.effects.length,0);
assert.equal(resolveElementReaction(target,'ice',30).bonus,0);
const immune={hp:20,effects:[{type:'poison',duration:2}]};
assert.equal(resolveElementReaction(immune,'fire',0).bonus,0);
assert.equal(immune.effects.length,1,'Imunidade não consome efeito');
const low={hp:2,effects:[{type:'poison',duration:1}]};
assert.equal(resolveElementReaction(low,'fire',100).bonus,2,'Não excede HP restante');
assert.equal(low.hp,0);
assert.match(observedElementLabel('fire',1.5),/Fraco/);

const state={bestiary:{}};
assert.equal(observeMonsterAction(base,{id:'heavy',name:'Golpe Devastador'},state),true);
assert.equal(observeMonsterAction(base,{id:'heavy',name:'Golpe Devastador'},state),true);
assert.equal(state.bestiary.Aranha.observedActions.heavy.count,2);
assert.equal(observeMonsterAffinity(base,'fire',1.5,state),true);
assert.equal(observeMonsterAffinity(base,'physical',.5,state),false);
assert.equal(observeMonsterAffinity(base,'ice',1,state),false);
assert.deepEqual(state.bestiary.Aranha.observedAffinities,{fire:1.5});
state.bestiary.Aranha.encounters=3;
state.bestiary.Aranha.wins=0;
state.bestiary.Aranha.losses=0;
rt.state=state;
const html=bestiaryUI();
assert.match(html,/Golpe Devastador/);
assert.match(html,/Padrão observado/);
assert.match(html,/Fogo: Fraco \(1.5x\)/);
assert.doesNotMatch(html,/Afinidades testadas:.*Gelo/);
const old={version:7,name:'Teste',cls:'guerreiro',stats:[8,2,3,4,8,3],lv:1,xp:0,gold:100,points:0,hp:80,mp:20,items:[],equip:{},materials:{},bosses:[],area:1,bestiary:structuredClone(state.bestiary)};
const loaded=normalizeSave(JSON.parse(JSON.stringify(old)));
assert.equal(loaded.bestiary.Aranha.observedActions.heavy.count,2);
assert.equal(loaded.bestiary.Aranha.observedAffinities.fire,1.5);
assert.equal(loaded.version,11,'Migração v7 para v8 preserva bestiário');
const combat=readFileSync(new URL('../js/combat.js',import.meta.url),'utf8');
const ui=readFileSync(new URL('../js/ui.js',import.meta.url),'utf8');
assert.match(combat,/consumeAnnouncedAction\(e\)/);
assert.match(combat,/selectAnnouncedAction\(e\)/);
assert.match(combat,/observeMonsterAction\(e,action\)/);
assert.match(combat,/resolveElementReaction\(e,element,damage\)/);
assert.match(ui,/combat-warning/);
assert.match(ui,/escape\(e.telegraph.message\)/);
assert.ok(!combat.includes('stance'), 'Não adiciona posturas de combate');
// Integração real do turno inimigo com o anúncio e sua execução no turno seguinte.
const {enemyTurn}=await import('../js/combat.js');
const {stats}=await import('../js/player.js');
rt.state=normalizeSave(old);
rt.state.lv=25;
rt.state.statistics.damageTaken=0;
rt.state.combat={enemy:{...structuredClone(base),archetype:'aggressive',telegraph:null,telegraphCooldown:0,guardTurns:0},effects:[],turn:0,guard:0};
rt.state.hp=stats().maxhp;
rt.log=[];
const roll=Math.random;
try{
 Math.random=()=>0;
 const hpBefore=rt.state.hp,enemyMp=rt.state.combat.enemy.mp;
 enemyTurn();
 assert.ok(rt.state.combat.enemy.telegraph?.kind==='monster','Anúncio integrado ao primeiro turno');
 assert.equal(rt.state.hp,hpBefore,'O primeiro turno apenas avisa');
 assert.equal(rt.state.combat.enemy.mp,enemyMp,'Anúncio não gasta recursos');
 assert.match(rt.log.join(' '),/ATAQUE ANUNCIADO/);
 enemyTurn();
 assert.equal(rt.state.combat.enemy.telegraph,null,'Ação preparada foi consumida');
 assert.ok(rt.state.combat.enemy.mp<enemyMp,'MP consumido quando a técnica acontece');
 assert.ok(rt.state.bestiary.Aranha.observedActions.element||rt.state.bestiary.Aranha.observedActions.heavy);
 assert.ok(rt.state.combat.enemy.telegraphCooldown>0);
}finally{Math.random=roll;}

console.log('OK: anúncios raros, resolução única, MP, recargas, reações limitadas, observações reais, bestiário e migração de salvamento v7 a v8.');
