import assert from 'node:assert/strict';
const storage=new Map();
globalThis.localStorage={getItem:key=>storage.get(key)??null,setItem:(key,value)=>storage.set(key,value),removeItem:key=>storage.delete(key)};
let onClick=null;
const app={innerHTML:'',addEventListener(name,listener){if(name==='click')onClick=listener},querySelector(){return null},querySelectorAll(){return []}};
globalThis.document={querySelector:s=>s==='#app'?app:null};
globalThis.window={addEventListener(){}};
globalThis.requestAnimationFrame=fn=>fn();
globalThis.setInterval=()=>0;
const {rt}=await import('../js/runtime.js');
const {newGame}=await import('../js/player.js');
const {catalogForShop,createCatalogItem}=await import('../js/equipment-catalog.js');
const {cityPrice}=await import('../js/city-life.js');
const {KEY}=await import('../js/data.js');
await import('../js/main.js');
newGame('Compras reais','mago');rt.area=1;rt.state.lv=20;rt.state.gold=10000;rt.screen='city';rt.shop='armor';
assert.equal(typeof onClick,'function');
const model=catalogForShop(0,'mago','armor').find(item=>item.armor===3&&item.slot==='body');
const preview=createCatalogItem(model);const cost=cityPrice(rt.state,0,preview.price);
const click=action=>{const button={disabled:false,dataset:{action}};onClick({target:{closest:()=>button}})};
const before=rt.state.gold;
click(`buyCatalog:${model.id}`);
assert.equal(rt.state.gold,before-cost);
assert.equal(rt.state.items.at(-1).catalogId,model.id);
const saved=JSON.parse(storage.get(KEY));
assert.equal(saved.items.at(-1).catalogId,model.id);
assert.equal(saved.gold,before-cost);
click(`buyCatalog:ep6-r7-armor-0`);
assert.equal(rt.state.gold,before-cost,'região bloqueada não cobra ouro');
console.log('OK: evento real de compra, preço anunciado igual ao cobrado, item correto, salvamento imediato e região bloqueada.');
